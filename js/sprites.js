/**
 * One sprite → an inline SVG data URI. Horizontal runs merge into single
 * rects, so a 12×12 drawing is a handful of shapes rather than 144.
 */
function toDataUri(grid, palette) {
  // Horizontal runs merge into one rect, and rects of the same colour share a
  // <g fill>, so a 12x12 drawing is a handful of shapes carrying one colour
  // each instead of 144 rects each repeating its own hex.
  const byColour = new Map();
  grid.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (!palette[ch]) { x++; continue; }
      let run = 1;
      while (row[x + run] === ch) run++;
      const colour = palette[ch];
      if (!byColour.has(colour)) byColour.set(colour, []);
      byColour.get(colour).push(`<rect x="${x}" y="${y}" width="${run}" height="1"/>`);
      x += run;
    }
  });
  const groups = [...byColour].map(([colour, rects]) => `<g fill="${colour}">${rects.join('')}</g>`);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 12 12" shape-rendering="crispEdges">${groups.join('')}</svg>`;
  // A data URI only needs %, #, <, > and " escaped. encodeURIComponent also
  // escapes every space, slash and quote-adjacent character, which roughly
  // doubles the string for no benefit.
  const escaped = svg.replace(/[%#<>"]/g, c => '%' + c.charCodeAt(0).toString(16).toUpperCase());
  return `data:image/svg+xml,${escaped}`;
}

const cache = new Map();

/**
 * Data URI for a game's 8-bit logo, or '' if it has none.
 * tone 'amber' is the default, for dark panels; 'ink' is for amber grounds.
 */
export function spriteFor(id, tone = 'amber') {
  const key = `${tone}:${id}`;
  if (cache.has(key)) return cache.get(key);
  const grid = SPRITES[id];
  const uri = grid ? toDataUri(grid, tone === 'ink' ? PALETTE_ON_AMBER : PALETTE) : '';
  cache.set(key, uri);
  return uri;
}

/** Ready-to-drop <img>, or '' — decorative, so it stays out of the a11y tree. */
export function spriteImg(id, cls = 'cart-sprite', tone = 'amber') {
  const uri = spriteFor(id, tone);
  return uri ? `<img class="${cls}" src="${uri}" alt="" aria-hidden="true" draggable="false">` : '';
}
