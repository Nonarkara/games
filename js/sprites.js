/**
 * Dr Non — Non-Gaming System · Cartridge sprites
 *
 * An 8-bit logo for every cartridge on the floor, drawn by hand, one
 * character per pixel, 12×12. No images are fetched and nothing is
 * AI-generated: the art IS the source, which is why it costs ~40 bytes a
 * game and stays sharp at any size.
 *
 * PALETTE — four values, and amber is the only hue.
 *   .  transparent
 *   #  amber   (--ax-red  #f59e0b)   the Move
 *   +  ink     (--ax-ink  #e6edf3)   eyes, highlights, the punchline pixel
 *   -  dim     (--ax-ink-3 #6b7785)  shading, ground, the thing being ignored
 *
 * Eighty-eight full-colour badges would drown the one amber the whole floor
 * is built around (§14 r1), so the jokes are carried by the drawing instead:
 * the brain doing a double-take, the frog that has clearly seen things, the
 * cup with X for eyes. Silly, on register, no rainbow.
 *
 * ONE NAMED EXCEPTION: 'stroop-match' uses r/b/g. That game is *about* the
 * ink being the wrong colour — a monochrome sprite for it would be a
 * drawing of nothing. Load-bearing, so it is allowed and written down here.
 */

